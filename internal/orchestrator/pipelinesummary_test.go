func TestRenderPipelineSummary_ReviewFixesDetailsBlock(t *testing.T) {
	stages := []daemon.StageResult{
		{Name: stageNameReview, Result: stageResultPass},
	}
	messages := map[string]string{
		stageNameReview: "review passed: 2 auto-fix(es) applied, 0 finding(s) await human approval",
	}
	fixes := []string{
		"Nested authorColors under gui as required by schema.",
		"Preserved unmanaged wildcard author colors.",
	}

	got := renderPipelineSummary(stages, messages, fixes)

	if !strings.Contains(got, "<summary><strong>Review fixes</strong></summary>") {
		t.Fatalf("expected a Review fixes details block, got:\n%s", got)
	}
	if !strings.Contains(got, "1. Nested authorColors under gui as required by schema.") {
		t.Fatalf("expected the first fix numbered, got:\n%s", got)
	}
	if !strings.Contains(got, "2. Preserved unmanaged wildcard author colors.") {
		t.Fatalf("expected the second fix numbered, got:\n%s", got)
	}
}

func TestRenderPipelineSummary_EmptyStagesReturnsEmpty(t *testing.T) {
	if got := renderPipelineSummary(nil, nil, nil); got != "" {
		t.Fatalf("expected empty summary for no stages, got:\n%s", got)
	}
}
