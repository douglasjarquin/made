package orchestrator

import (
	"strings"
	"testing"

	"github.com/douglasjarquin/made/internal/daemon"
)

func TestRenderPipelineSummary_AllPassedNoFixes(t *testing.T) {
	stages := []daemon.StageResult{
		{Name: stageNameIntent, Result: stageResultPass},
		{Name: stageNameRebase, Result: stageResultPass},
		{Name: stageNameReview, Result: stageResultPass},
		{Name: stageNameTest, Result: stageResultPass},
		{Name: stageNameDocument, Result: stageResultPass},
		{Name: stageNameLint, Result: stageResultPass},
		{Name: stageNamePush, Result: stageResultPass},
	}
	messages := map[string]string{
		stageNameReview: "review passed: 0 auto-fix(es) applied, 0 finding(s) await human approval",
	}

	got := renderPipelineSummary(stages, messages, nil)

	if !strings.Contains(got, "Generated by [`made`](https://github.com/douglasjarquin/made)") {
		t.Fatalf("expected made attribution line, got:\n%s", got)
	}
	if !strings.Contains(got, "| Stage | Status | Notes |") {
		t.Fatalf("expected a status table header, got:\n%s", got)
	}
	if !strings.Contains(got, "| Intent | ✅ Passed | |") {
		t.Fatalf("expected a blank-notes Intent row, got:\n%s", got)
	}
	if !strings.Contains(got, "| Review | ✅ Passed | review passed: 0 auto-fix(es) applied, 0 finding(s) await human approval |") {
		t.Fatalf("expected the review row to carry its real message, got:\n%s", got)
	}
	if strings.Contains(got, "<details>") {
		t.Fatalf("expected no review-fixes details block when nothing was fixed, got:\n%s", got)
	}
}

func TestRenderPipelineSummary_FailedStageShowsMessage(t *testing.T) {
	stages := []daemon.StageResult{
		{Name: stageNameIntent, Result: stageResultPass},
		{Name: stageNameRebase, Result: stageResultFail},
	}
	messages := map[string]string{
		stageNameRebase: "rebase: conflict in file.go",
	}

	got := renderPipelineSummary(stages, messages, nil)

	if !strings.Contains(got, "| Rebase | ❌ Failed | rebase: conflict in file.go |") {
		t.Fatalf("expected the failed stage to show its message, got:\n%s", got)
	}
}

